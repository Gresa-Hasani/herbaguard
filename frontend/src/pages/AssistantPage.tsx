import { useEffect, useRef, useState } from 'react'

import { CitationCard } from '../components/CitationCard'
import { ClassBadge } from '../components/ClassBadge'
import { Icon } from '../components/icons'
import {
  Alert,
  Badge,
  Button,
  Disclosure,
  EmptyState,
  PageHeader,
  SectionHeading,
  Spinner,
} from '../components/ui'
import { useAsk } from '../hooks/useApi'
import { askTimeoutMs, describeAskFailure } from '../lib/ask'
import { humanize } from '../lib/format'
import { recordType } from '../lib/citations'
import type { AskResponse, Citation } from '../lib/types'

const STATUS_LABELS: Record<AskResponse['status'], string> = {
  answered: 'Answered from cited evidence',
  insufficient_evidence: 'Insufficient evidence to answer',
  rejected_by_validation: 'Answer failed validation',
  declined_dosing: 'Dosing advice declined',
  emergency_referral: 'Emergency referral',
}

const EXAMPLES = [
  'What does the evidence say about St John’s wort and warfarin?',
  'Which sources support the use of ginger for nausea?',
  'What interactions are documented for ginkgo?',
]

/** Citation chip colour follows the kind of evidence the label refers to. */
const CHIP_TONES: Record<string, string> = {
  C: 'border-forest-600/30 bg-forest-50 text-forest-700',
  S: 'border-teal-600/30 bg-teal-50 text-teal-700',
  M: 'border-ev-clinical/30 bg-[#e9eef8] text-ev-clinical',
  E: 'border-ev-clinical/30 bg-[#e9eef8] text-ev-clinical',
  F: 'border-line-strong bg-surface-2 text-ink-soft',
  X: 'border-ev-supplementary/30 bg-[#ece9f6] text-ev-supplementary',
  H: 'border-ev-supplementary/30 bg-[#ece9f6] text-ev-supplementary',
  U: 'border-ev-supplementary/30 bg-[#ece9f6] text-ev-supplementary',
  P: 'border-clay-600/40 bg-clay-50 text-clay-700',
}

function CitationChip({ label, kind }: { label: string; kind?: string }) {
  const description = kind
    ? `Reference ${label}: ${kind}. Opens the source record below.`
    : `Reference ${label}`
  return (
    <a
      href={`#citation-${label}`}
      title={description}
      aria-label={description}
      className={`inline-flex min-w-7 items-center justify-center rounded-md border px-1.5 py-0.5 text-xs font-semibold transition-transform hover:-translate-y-0.5 ${
        CHIP_TONES[label.charAt(0)] ?? CHIP_TONES.F
      }`}
    >
      {label}
    </a>
  )
}

/** Prepared answers return within seconds, so the long-wait explanation appears only after this. */
const LONG_WAIT_SECONDS = 5

function WaitingPanel({
  elapsed,
  timeoutMinutes,
  onCancel,
}: {
  elapsed: number
  timeoutMinutes: number
  onCancel: () => void
}) {
  return (
    <div className="animate-pop overflow-hidden rounded-2xl border border-line bg-surface shadow-soft">
      <div className="flex flex-wrap items-center gap-6 p-6">
        <div className="relative flex h-16 w-16 shrink-0 items-center justify-center">
          <span className="pulse-ring absolute inset-0 rounded-full bg-forest-500/30" />
          <span className="relative flex h-14 w-14 items-center justify-center rounded-full bg-forest-800 text-forest-100">
            <Icon name="leaf" className="sway h-6 w-6" />
          </span>
        </div>
        <div className="min-w-0 flex-1">
          <Spinner label="Retrieving evidence and validating an answer…" />
          {elapsed >= LONG_WAIT_SECONDS ? (
            <p className="mt-2 text-sm leading-relaxed text-muted">
              Answers are generated by a local language model and can take several minutes,
              especially for the first question after the model has been idle. The answer will only
              appear after retrieval and validation complete; no partial or fabricated text is
              shown. This page waits up to {timeoutMinutes} minutes.
            </p>
          ) : null}
        </div>
        <div className="flex flex-col items-end gap-3">
          <Button variant="secondary" size="sm" icon="stop" onClick={onCancel}>
            Cancel request
          </Button>
        </div>
      </div>
    </div>
  )
}

export function AssistantPage() {
  const [question, setQuestion] = useState('')
  const [asked, setAsked] = useState('')
  const [elapsed, setElapsed] = useState(0)
  const ask = useAsk()
  // Synchronous guard: isPending only flips after the next render, so a fast double click or
  // Enter+click could otherwise start two multi-minute generations.
  const inFlight = useRef(false)
  const controller = useRef<AbortController | null>(null)
  const timeoutSeconds = Math.round(askTimeoutMs() / 1000)

  useEffect(() => {
    if (!ask.isPending) {
      setElapsed(0)
      return
    }
    const startedAt = Date.now()
    const timer = setInterval(() => setElapsed(Math.floor((Date.now() - startedAt) / 1000)), 1000)
    return () => clearInterval(timer)
  }, [ask.isPending])

  // Leaving the page cancels the request instead of leaving a CPU job nobody is waiting for.
  useEffect(() => () => controller.current?.abort(), [])

  function send(text: string) {
    if (!text || inFlight.current) return
    inFlight.current = true
    const abort = new AbortController()
    controller.current = abort
    setAsked(text)
    ask.mutate(
      { question: text, signal: abort.signal },
      {
        onSettled: () => {
          inFlight.current = false
          controller.current = null
        },
      },
    )
  }

  function submit(event: React.FormEvent<HTMLFormElement>) {
    event.preventDefault()
    send(question.trim())
  }

  function cancel() {
    controller.current?.abort()
  }

  const data = ask.data
  const failure = ask.error ? describeAskFailure(ask.error, timeoutSeconds) : null
  const citations = data?.citations ?? []
  const citationByLabel = new Map(citations.map((citation) => [citation.label, citation]))
  const clinicalCitations = citations.filter((citation) => citation.kind !== 'product_label')
  const labelCitations = citations.filter((citation) => citation.kind === 'product_label')
  const idle = !data && !ask.isPending && !failure

  return (
    <div className="space-y-8">
      <PageHeader
        icon="chat"
        eyebrow="Retrieval-augmented, citation-checked"
        title="Evidence Assistant"
        aside={
          <Badge tone="info" className="self-start">
            <Icon name="shield" className="h-3.5 w-3.5" />
            Validated before display
          </Badge>
        }
      >
        <p>
          Ask about herb–drug evidence, mechanisms or source coverage. The backend retrieves stored
          evidence, answers only from that context and validates the response before it is shown.
          Answers are not medical advice.
        </p>
      </PageHeader>

      <section
        aria-label="Ask the evidence assistant"
        className="rounded-2xl border border-line bg-surface p-5 shadow-soft sm:p-6"
      >
        <form onSubmit={submit}>
          <label htmlFor="assistant-question" className="block text-sm font-semibold text-ink">
            Your question
          </label>
          <textarea
            id="assistant-question"
            value={question}
            onChange={(event) => setQuestion(event.target.value)}
            rows={3}
            maxLength={1000}
            placeholder="e.g. What does the evidence say about St John’s wort and warfarin?"
            className="mt-2 w-full resize-y rounded-xl border border-line-strong bg-canvas px-4 py-3 font-display text-lg leading-snug text-ink transition-shadow placeholder:font-sans placeholder:text-base placeholder:text-muted/70 focus:border-teal-500 focus:outline-none focus:ring-4 focus:ring-teal-500/15"
          />
          <div className="mt-3 flex flex-wrap items-center justify-between gap-3">
            <p className="max-w-xl text-xs leading-relaxed text-muted">
              {question.trim().length}/1000 characters. Questions asking for a personal diagnosis,
              dose or emergency advice are declined by the backend.
            </p>
            <Button type="submit" size="lg" disabled={!question.trim() || ask.isPending} iconEnd="arrow">
              {ask.isPending ? 'Working…' : 'Ask'}
            </Button>
          </div>
        </form>

        <div className="mt-5 border-t border-line pt-4">
          <p className="text-xs font-semibold uppercase tracking-wider text-muted">Try asking</p>
          <ul className="mt-3 grid gap-2.5 md:grid-cols-3">
            {EXAMPLES.map((example) => (
              <li key={example}>
                <button
                  type="button"
                  onClick={() => setQuestion(example)}
                  className="group flex h-full w-full items-start gap-2.5 rounded-lg border border-line bg-surface-2 p-3 text-left text-sm text-ink-soft transition-all hover:-translate-y-0.5 hover:border-forest-500/50 hover:bg-forest-50 hover:text-ink"
                >
                  <Icon name="chat" className="mt-0.5 h-4 w-4 text-forest-500" />
                  {example}
                </button>
              </li>
            ))}
          </ul>
        </div>
      </section>

      <div aria-live="polite" className="space-y-6">
        {ask.isPending || data || failure ? (
          <div className="ml-auto max-w-2xl rounded-2xl rounded-tr-md bg-forest-800 px-5 py-3 text-forest-50 shadow-soft">
            <p className="text-[11px] font-semibold uppercase tracking-wider text-forest-300">
              Question asked
            </p>
            <p className="mt-0.5 font-display text-lg leading-snug">{asked}</p>
          </div>
        ) : null}

        {ask.isPending ? (
          <WaitingPanel
            elapsed={elapsed}
            timeoutMinutes={Math.round(timeoutSeconds / 60)}
            onCancel={cancel}
          />
        ) : null}

        {failure ? (
          <Alert
            tone={failure.kind === 'cancelled' ? 'warn' : 'danger'}
            role="alert"
            title={failure.title}
          >
            <p>{failure.message}</p>
            {failure.requestId ? (
              <p className="mt-1 text-xs">Request ID: {failure.requestId}</p>
            ) : null}
            <p className="mt-2 text-xs">
              No answer is being shown, because none was successfully retrieved. Do not treat this
              as evidence that a combination is safe. Your question has been kept.
            </p>
            {failure.retryable ? (
              <Button
                size="sm"
                icon="retry"
                className="mt-3"
                onClick={() => send(question.trim())}
                disabled={!question.trim() || ask.isPending}
              >
                Retry question
              </Button>
            ) : null}
          </Alert>
        ) : null}

        {data ? (
          <div className="animate-pop space-y-6">
            <section
              aria-labelledby="answer-heading"
              className="space-y-4 rounded-2xl border border-line bg-surface p-5 shadow-soft sm:p-7"
            >
              <div className="flex flex-wrap items-center justify-between gap-2">
                <h2
                  id="answer-heading"
                  className="font-display text-2xl font-semibold text-ink"
                >
                  Answer
                </h2>
                <div className="flex flex-wrap items-center gap-2">
                  <Badge tone={data.status === 'answered' ? 'brand' : 'warn'}>
                    {STATUS_LABELS[data.status]}
                  </Badge>
                  <Badge tone="neutral">Intent: {humanize(data.intent)}</Badge>
                </div>
              </div>

              {data.status === 'emergency_referral' ? (
                <Alert tone="danger" role="alert" title="Seek urgent medical help">
                  <p>
                    This question suggests a possible emergency. Contact local emergency services or
                    a poison centre now. HerbaGuard cannot provide emergency care.
                  </p>
                </Alert>
              ) : null}

              {data.status === 'declined_dosing' ? (
                <Alert tone="warn" title="Dosing advice is out of scope">
                  <p>
                    HerbaGuard does not provide doses or personal treatment plans. The response below
                    is limited to evidence and safety information.
                  </p>
                </Alert>
              ) : null}

              {data.status === 'insufficient_evidence' ? (
                <Alert tone="warn" title="The evidence was insufficient to answer">
                  <p>
                    No answer is being inferred beyond the retrieved sources. Missing evidence is not
                    evidence of safety.
                  </p>
                </Alert>
              ) : null}

              {data.status === 'rejected_by_validation' ? (
                <Alert tone="danger" title="The draft answer did not pass validation">
                  <p>
                    Unsupported or unsafe text was removed before display. Treat the answer as
                    incomplete and rely on the citations and limitations below.
                  </p>
                </Alert>
              ) : null}

              {data.paragraphs.length > 0 ? (
                <div className="space-y-4">
                  {data.paragraphs.map((paragraph, index) => (
                    <div
                      key={index}
                      className="border-l-2 border-forest-300 pl-4 sm:pl-5"
                    >
                      <p className="font-display text-[17px] leading-relaxed text-ink">
                        {paragraph.text}
                      </p>
                      {paragraph.citations.length > 0 ? (
                        <p className="mt-2.5 flex flex-wrap items-center gap-1.5 text-xs text-muted">
                          <span className="font-medium">Citations:</span>
                          {paragraph.citations.map((label) => (
                            <CitationChip
                              key={label}
                              label={label}
                              kind={
                                citationByLabel.has(label)
                                  ? recordType(citationByLabel.get(label) as Citation).label
                                  : undefined
                              }
                            />
                          ))}
                        </p>
                      ) : null}
                    </div>
                  ))}
                </div>
              ) : data.answer ? (
                <p className="whitespace-pre-line border-l-2 border-forest-300 pl-4 font-display text-[17px] leading-relaxed text-ink sm:pl-5">
                  {data.answer}
                </p>
              ) : data.status !== 'insufficient_evidence' ? (
                <EmptyState title="No answer text was returned" icon="file">
                  <p>
                    The backend did not return an answer for this question. The citations and
                    limitations, if any, are shown below without interpretation.
                  </p>
                </EmptyState>
              ) : null}

              {data.entities.length > 0 ? (
                <div className="flex flex-wrap items-center gap-2 border-t border-line pt-4">
                  <span className="text-xs font-medium text-muted">Resolved entities:</span>
                  {data.entities.map((entity, index) => (
                    <Badge key={`${entity.kind}-${entity.name}-${index}`} tone="neutral">
                      {humanize(entity.kind)}: {entity.name}
                      {entity.identifier ? ` (${entity.identifier})` : ''}
                    </Badge>
                  ))}
                </div>
              ) : null}
            </section>

            {data.classification.length > 0 ? (
              <div className="space-y-3">
                <h3 className="font-display text-xl font-semibold text-ink">
                  Deterministic classifications used in this answer
                </h3>
                <ul className="grid gap-3 md:grid-cols-2">
                  {data.classification.map((item, index) => (
                    <li
                      key={`${item.herb}-${item.drug}-${index}`}
                      className="rounded-xl border border-line bg-surface p-4 shadow-soft"
                    >
                      <div className="flex flex-wrap items-center justify-between gap-2">
                        <p className="font-medium text-ink">
                          {item.herb} + {item.drug}
                        </p>
                        <ClassBadge
                          letter={item.interaction_class}
                          label={item.class_label}
                          size="sm"
                        />
                      </div>
                      <p className="mt-2 text-sm leading-relaxed text-ink-soft">
                        {item.explanation}
                      </p>
                      {item.severity_wordings.length > 0 ? (
                        <p className="mt-2 text-xs text-muted">
                          Source wording:{' '}
                          {item.severity_wordings.map((wording) => `“${wording}”`).join('; ')}
                        </p>
                      ) : null}
                    </li>
                  ))}
                </ul>
              </div>
            ) : null}

            {data.limitations.length > 0 ? (
              <section className="rounded-xl border border-clay-600/25 bg-clay-50 p-5">
                <h2 className="flex items-center gap-2 font-display text-lg font-semibold text-clay-800">
                  <Icon name="alert" className="h-5 w-5" />
                  Limitations and uncertainty
                </h2>
                <ul className="mt-3 space-y-2 text-sm text-ink-soft">
                  {data.limitations.map((limitation) => (
                    <li key={limitation} className="flex gap-2.5">
                      <span className="mt-2 h-1.5 w-1.5 shrink-0 rounded-full bg-clay-600" />
                      {limitation}
                    </li>
                  ))}
                </ul>
              </section>
            ) : null}

            {data.validation.length > 0 ? (
              <Disclosure title="Validation record">
                <p className="text-xs text-muted">
                  Rules applied to the generated draft. Removed text is not shown.
                </p>
                <ul className="mt-3 space-y-2 text-sm">
                  {data.validation.map((item, index) => (
                    <li key={`${item.rule}-${index}`} className="rounded-lg bg-surface-2 p-3">
                      <span className="font-semibold text-ink">{humanize(item.severity)}</span> ·{' '}
                      <span className="font-mono text-xs">{item.rule}</span>
                      <p className="mt-0.5 text-muted">{item.message}</p>
                    </li>
                  ))}
                </ul>
              </Disclosure>
            ) : null}

            <section aria-label="Citations" className="space-y-4">
              <SectionHeading
                eyebrow="Traceability"
                title="Citations"
                description="Each reference ID (C1, S3, X2…) ties a statement in the answer to its source record. It is a label, not an evidence-quality rating. Document type is shown, not a quality score."
                action={<Badge>{clinicalCitations.length} clinical / other</Badge>}
              />
              {clinicalCitations.length > 0 ? (
                <ol className="space-y-3">
                  {clinicalCitations.map((citation) => (
                    <CitationCard key={citation.label} citation={citation} />
                  ))}
                </ol>
              ) : (
                <Alert tone="warn" title="No clinical citations were returned">
                  <p>
                    This answer has no cited clinical or regulatory evidence. Do not rely on it as
                    support for a conclusion.
                  </p>
                </Alert>
              )}
            </section>

            {labelCitations.length > 0 ? (
              <section aria-label="Product labels (NIH DSLD)" className="space-y-4">
                <SectionHeading
                  eyebrow="Supplementary source"
                  title="Product labels (NIH DSLD)"
                  description="Manufacturer labels returned as citations. They are not clinical evidence or HerbaGuard findings."
                />
                <Alert tone="warn" title="Product-label information">
                  <p>
                    Manufacturer label information — not clinical evidence, not a HerbaGuard finding.
                    Licence unverified.
                  </p>
                </Alert>
                <ol className="space-y-3">
                  {labelCitations.map((citation) => (
                    <CitationCard key={citation.label} citation={citation} />
                  ))}
                </ol>
              </section>
            ) : null}

            {data.citations.length === 0 ? (
              <p className="text-xs text-muted">
                No citation labels were returned. Answer text without citations should not be relied
                upon.
              </p>
            ) : null}

            {data.retrieval && data.retrieval.notes.length > 0 ? (
              <ul className="space-y-1 text-xs text-muted">
                {data.retrieval.notes.map((note) => (
                  <li key={note}>{note}</li>
                ))}
              </ul>
            ) : null}

            {data.personal_advice_requested ? (
              <p className="text-xs font-medium text-clay-700">
                The question requested personal medical advice; the backend applied its advice
                guardrails.
              </p>
            ) : null}

            <Alert tone="neutral" role="note">
              <p>{data.disclaimer}</p>
            </Alert>
          </div>
        ) : null}
      </div>

      {idle ? (
        <EmptyState title="No answer yet" icon="chat">
          <p>
            Ask a question to retrieve cited evidence. The assistant will not invent an answer when
            the retrieval set is insufficient.
          </p>
        </EmptyState>
      ) : null}

      <p className="text-xs text-muted">
        Answers are generated only after retrieval. The backend applies validation rules, and this
        interface displays its status and limitations without editing the answer.
      </p>
    </div>
  )
}
